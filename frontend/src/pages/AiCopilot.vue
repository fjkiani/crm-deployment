<script setup>
import { ref, nextTick } from 'vue'

const loading = ref(false)
const error = ref('')
const results = ref([])
const company = ref('')
const domain = ref('')
const intel = ref(null)

// ── Farfalle Chat State ──────────────────────────────
const chatInput = ref('')
const chatMessages = ref([])
const chatLoading = ref(false)
const chatSources = ref([])

function getFarfalleBase() {
  if (window.FARFALLE_BASE) return String(window.FARFALLE_BASE)
  // EAIA backend has Farfalle-compatible /chat endpoint
  return 'http://localhost:8001'
}

// ── Company Intelligence ──────────────────────────────
async function analyze() {
  loading.value = true
  error.value = ''
  intel.value = null
  try {
    const base = getFarfalleBase()
    const resp = await fetch(`${base}/intel/enrich_lead`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ company: company.value, domain: domain.value })
    })
    if (!resp.ok) throw new Error(`Intel failed (${resp.status})`)
    intel.value = await resp.json()
  } catch (e) {
    error.value = e?.message || 'Failed — is Farfalle running?'
  } finally {
    loading.value = false
  }
}

// ── Farfalle SSE Chat ──────────────────────────────
async function sendChat() {
  const query = chatInput.value.trim()
  if (!query || chatLoading.value) return

  chatMessages.value.push({ role: 'user', content: query })
  chatInput.value = ''
  chatLoading.value = true
  chatSources.value = []

  // Add placeholder for assistant response
  const assistantIdx = chatMessages.value.length
  chatMessages.value.push({ role: 'assistant', content: '', sources: [], loading: true })

  await nextTick()
  scrollChatToBottom()

  try {
    const base = getFarfalleBase()
    const resp = await fetch(`${base}/chat`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        query: query,
        history: chatMessages.value.slice(0, -1).map(m => ({
          content: m.content,
          role: m.role
        })),
        model: 'gpt-4o-mini',
        pro_search: false,
      })
    })

    if (!resp.ok) throw new Error(`Chat failed (${resp.status})`)

    const reader = resp.body.getReader()
    const decoder = new TextDecoder()
    let buffer = ''

    while (true) {
      const { done, value } = await reader.read()
      if (done) break

      buffer += decoder.decode(value, { stream: true })
      const lines = buffer.split('\n')
      buffer = lines.pop() || ''

      for (const line of lines) {
        if (!line.startsWith('data:')) continue
        const jsonStr = line.slice(5).trim()
        if (!jsonStr) continue

        try {
          const evt = JSON.parse(jsonStr)
          const data = evt.data || evt

          if (data.event_type === 'text-chunk' && data.text) {
            chatMessages.value[assistantIdx].content += data.text
            scrollChatToBottom()
          } else if (data.event_type === 'search-results' && data.results) {
            chatMessages.value[assistantIdx].sources = data.results.map(r => ({
              title: r.title,
              url: r.url
            }))
            chatSources.value = chatMessages.value[assistantIdx].sources
          } else if (data.event_type === 'related-queries' && data.related_queries) {
            chatMessages.value[assistantIdx].relatedQueries = data.related_queries
          }
        } catch {
          // Skip malformed SSE lines
        }
      }
    }
  } catch (e) {
    chatMessages.value[assistantIdx].content = `Error: ${e.message}. Is Farfalle running at ${getFarfalleBase()}?`
    chatMessages.value[assistantIdx].isError = true
  } finally {
    chatMessages.value[assistantIdx].loading = false
    chatLoading.value = false
  }
}

function scrollChatToBottom() {
  nextTick(() => {
    const el = document.querySelector('.chat-messages')
    if (el) el.scrollTop = el.scrollHeight
  })
}

function askFollowUp(q) {
  chatInput.value = q
  sendChat()
}

// ── CRM Integration ──────────────────────────────
async function saveToCRM() {
  if (!intel.value) return
  loading.value = true
  error.value = ''
  try {
    const noteContent = `# Intelligence: ${intel.value.company}\n\n## Summary\n${intel.value.summary.map(s => `- ${s}`).join('\n')}\n\n## Sources\n${(intel.value.results?.flatMap(r => r.sources) || []).map(s => `- [${s.title}](${s.url})`).join('\n')}\n\n---\n*Generated by AI Copilot on ${new Date().toLocaleString()}*`
    await frappe.call({
      method: 'frappe.client.insert',
      args: {
        doc: {
          doctype: 'FCRM Note',
          title: `AI Intel: ${intel.value.company}`,
          content: noteContent,
        }
      }
    })
    alert('Intelligence saved to CRM Notes!')
  } catch (e) {
    error.value = e?.message || 'Failed to save'
  } finally {
    loading.value = false
  }
}

async function demoListOpenLeads() {
  loading.value = true
  error.value = ''
  results.value = []
  try {
    const res = await frappe.call({
      method: 'crm.api.doc.get_data',
      args: {
        doctype: 'CRM Lead',
        filters: { converted: ['=', 0] },
        order_by: 'modified desc',
        page_length: 10
      }
    })
    results.value = res.data?.data || []
  } catch (e) {
    error.value = e?.message || 'Failed'
  } finally {
    loading.value = false
  }
}
</script>

