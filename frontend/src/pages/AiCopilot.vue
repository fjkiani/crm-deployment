<script>
export default {
  name: 'AiCopilot',
  methods: {
    formatMessage(content) {
      if (!content) return ''
      return content
        .replace(/\n/g, '<br>')
        .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
        .replace(/\*(.*?)\*/g, '<em>$1</em>')
    }
  }
}
</script>

